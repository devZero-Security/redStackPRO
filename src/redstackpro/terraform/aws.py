"""The AWS backend.

The module blocks are mechanical: a node becomes a module call the same way it
does on GCP. The firewall is not.

GCP restricts a source by network tag. A tag is a string, so a rule names a host
without depending on the host resource, and one rule carries a list of sources.
AWS restricts by security group reference, so the group has to exist as a
resource before a rule can point at it, and a rule carries exactly one source.
Three senders to one collector is one rule on GCP and three here.

That is the provider abstraction leaking, and 0015 says it leaks here.
"""

from .plan import (  # noqa: F401  GenerationError re-exported
    GenerationError, align, operator_hosts_hcl, time_provider)

# AMI owners and name patterns rather than ids, because an id is per region and
# the region is a variable. The module resolves them with a data source.
# Debian 13, not 12: 12 ships Python 3.11 and certipy-ad 5.x requires 3.12, so
# the toolkit silently fell back to a 4.x build that could not even start. See
# the note in gcp.py. Same Debian-owned account; only the name pattern moves.
DEFAULT_IMAGES = {
    "debian": ("136693071363", "debian-13-amd64-*"),
    # Kali publishes its own images, so os kali gets a real Kali box on AWS the
    # same as it does on GCP. The listing needs a one time subscription on the
    # account, which is an account action rather than something an export can
    # do: redStackPRO generates code and touches no account. The README says so.
    # The name carries a debian- prefix (the images are Debian-derived) and the
    # owner is the Marketplace publisher the subscription grants access under.
    "kali": ("679593333241", "debian-kali-last-snapshot-amd64-*"),
    "windows": ("amazon", "Windows_Server-2022-English-Full-Base-*"),
}

# The AD range names a specific Windows Server build per host. Each maps to the
# Marketplace base image for that build; an unrecognized or unset build falls
# back to 2022, the same default the attack side's bare "windows" resolves to.
#
# 2016 is pinned to the 2019 base image on purpose: Windows Server 2016 reaches
# Microsoft end-of-support on 2027-01-12, after which AWS stops publishing the
# 2016 base AMI and the data-source lookup would return no results. Forcing 2016
# to 2019 keeps every lab that still names 2016 (a shipped template or a custom
# range) deployable, with the closest behaviour and least default hardening.
WINDOWS_IMAGES = {
    "windows_server_2016": ("amazon", "Windows_Server-2019-English-Full-Base-*"),
    "windows_server_2019": ("amazon", "Windows_Server-2019-English-Full-Base-*"),
    "windows_server_2022": ("amazon", "Windows_Server-2022-English-Full-Base-*"),
}

DEFAULT_MACHINE = {
    "collector": "t3.large",
    "operator": "t3.large",
    # AD hosts. A DC promotion and a member join are memory hungry; a workstation
    # is lighter. A SIEM ingests and indexes, so it matches the collector.
    "dc": "t3.large",
    "srv": "t3.large",
    "wks": "t3.medium",
    "siem": "t3.large",
}


def image_for(plan, node):
    kind, overlay = node["kind"], node.get("overlay", {})
    if kind == "operator":
        return DEFAULT_IMAGES[overlay.get("os", "debian")]
    # A DC, member server, or workstation is Windows unless its os says otherwise
    # (a Linux member such as GOAD's lx01/syrax, or a SIEM). is_windows already
    # encodes that default: the AD host kinds are Windows when no os is set, and a
    # host whose os names linux is not.
    if plan.is_windows(node):
        return WINDOWS_IMAGES.get(overlay.get("os"), DEFAULT_IMAGES["windows"])
    return DEFAULT_IMAGES["debian"]


def files(plan):
    return {
        "terraform/versions.tf": _versions(plan),
        "terraform/variables.tf": _variables(plan.region),
        "terraform/terraform.tfvars": _tfvars(plan),
        "terraform/main.tf": _main(plan),
        "terraform/firewall.tf": _firewall(plan),
    }


