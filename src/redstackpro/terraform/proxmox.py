"""The Proxmox backend (bpg/proxmox).

On-prem per 0003. A Proxmox host has no allocated public address and no managed
private DNS, and outbound routing is a precondition of the host network rather
than a resource (see the registry). So a "network" is a routing domain realised
as a VLAN, a "segment" is a VLAN carrying a CIDR, and a peers edge has nothing to
compile to. Proxmox has no cloud DHCP either, so each host takes a static address
allocated from its segment here.

Linux hosts come up from a cloud image with cloud-init (the strong path). Windows
hosts boot an operator-supplied ISO with the VirtIO drivers and an autounattend
answer file, then are provisioned over WinRM the same as the other backends. The
firewall is the Proxmox VM firewall, driven by the same edges. See 0015.
"""

import ipaddress

