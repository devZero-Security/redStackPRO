# Cloud images for the Linux builds, downloaded to the ISO datastore at apply.
# Windows has no cloud image, so a Windows host takes an operator-supplied ISO
# (proxmox_windows_iso_url) and installs unattended.
# Debian 13 (trixie) by default; see the note in gcp.py for the Python floor
# that forced it. bookworm stays reachable for a topology that names debian_12.
LINUX_IMAGES = {
    "debian": "https://cloud.debian.org/images/cloud/trixie/latest/debian-13-genericcloud-amd64.qcow2",
    "debian_13": "https://cloud.debian.org/images/cloud/trixie/latest/debian-13-genericcloud-amd64.qcow2",
    "debian_12": "https://cloud.debian.org/images/cloud/bookworm/latest/debian-12-genericcloud-amd64.qcow2",
    "ubuntu_2204": "https://cloud-images.ubuntu.com/jammy/current/jammy-server-cloudimg-amd64.img",
    "ubuntu_2004": "https://cloud-images.ubuntu.com/focal/current/focal-server-cloudimg-amd64.img",
    # Trixie rather than bookworm: Kali tracks Debian testing, so the newer base
    # is the closer stand-in, and it is the same interpreter the toolchain is
    # resolved against everywhere else.
    "kali": "https://cloud.debian.org/images/cloud/trixie/latest/debian-13-genericcloud-amd64.qcow2",
}

# Windows builds all boot the same operator-supplied ISO; the build only labels
# the guest. GCP has no client image either, and here the ISO is the operator's,
# so a workstation and a server differ only in the answer file's edition.
WINDOWS_BUILDS = {
    "windows_server_2016", "windows_server_2019", "windows_server_2022",
    "windows_10", "windows_11", "windows",
}

# Machine sizing per kind, in (cores, memory_mb). Overridable in tfvars.
DEFAULT_MACHINE = {
    "collector": (2, 4096),
    "operator": (2, 4096),
    "dc": (2, 4096),
    "srv": (2, 4096),
    "wks": (2, 2048),
    "siem": (4, 8192),
}


def is_windows(node):
    return node.get("overlay", {}).get("os", "") in WINDOWS_BUILDS \
        or (node["kind"] in ("dc", "srv", "wks")
            and not node.get("overlay", {}).get("os", "").startswith(("debian", "ubuntu", "linux")))


def image_url_for(node):
    overlay = node.get("overlay", {})
    if node["kind"] == "operator":
        return LINUX_IMAGES.get(overlay.get("os", "debian"), LINUX_IMAGES["debian"])
    return LINUX_IMAGES.get(overlay.get("os"), LINUX_IMAGES["debian"])


