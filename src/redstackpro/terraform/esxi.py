# ---------------------------------------------------------------- addressing

def _segment_plan(plan):
    """A host that declares internal_ip on its overlay (e.g. a range locking
    to GOAD's canonical octets, see 0055) gets that exact address; every other
    host in the segment auto-assigns the next free one, skipping whatever the
    pinned hosts already claimed. Auto-assignment starts at .10 in segment
    order, matching the other on-prem backends."""
    seg_vlan, host_ip = {}, {}
    for i, seg in enumerate(plan.segments()):
        seg_vlan[seg["id"]] = 100 + i
    for seg in plan.segments():
        net = ipaddress.ip_network(seg["overlay"]["cidr"])
        here = sorted((h for h in plan.hosts()
                       if plan.primary_segment(h) == seg["id"]),
                      key=lambda n: n["id"])
        pinned = {h["id"]: h["overlay"]["internal_ip"] for h in here
                  if h.get("overlay", {}).get("internal_ip")}
        taken = set(pinned.values())
        auto = (str(net[i]) for i in range(10, net.num_addresses - 1)
                if str(net[i]) not in taken)
        for h in here:
            host_ip[h["id"]] = pinned.get(h["id"]) or next(auto)
    return seg_vlan, host_ip


def _prefixlen(cidr):
    return ipaddress.ip_network(cidr).prefixlen


def _gateway(cidr):
    return str(ipaddress.ip_network(cidr)[1])


# ---------------------------------------------------------------- root module

def _main(plan):
    is_range = plan.is_range()
    seg_vlan, host_ip = _segment_plan(plan)

    lines = [
        "# Generated by redStackPRO. Do not edit.",
        "# One module block per node. Inter module references resolve at apply",
        "# time on your machine, because redStackPRO never runs Terraform. See 0001.",
        "",
        "# Deploy-wide vSphere lookups, resolved once and passed to the modules.",
        'data "vsphere_datacenter" "dc" {',
        "  name = var.datacenter",
        "}",
        "",
        'data "vsphere_datastore" "ds" {',
        "  name          = var.datastore",
        "  datacenter_id = data.vsphere_datacenter.dc.id",
        "}",
        "",
        'data "vsphere_resource_pool" "pool" {',
        "  name          = var.resource_pool",
        "  datacenter_id = data.vsphere_datacenter.dc.id",
        "}",
        "",
        'data "vsphere_host" "host" {',
        "  name          = var.esxi_host",
        "  datacenter_id = data.vsphere_datacenter.dc.id",
        "}",
    ]

    if is_range:
        lines += [
            "",
            'resource "random_password" "lab" {',
            "  length           = 20",
            "  special          = true",
            '  override_special = "!@#-_=+"',
            '  min_special      = 1',
            "}",
            "",
            'resource "tls_private_key" "guacamole" {',
            '  algorithm = "ED25519"',
            "}",
            "",
            "locals {",
            "  lab_password = var.lab_password != \"\" ? var.lab_password : random_password.lab.result",
            "}",
        ]

    # A network is a routing domain with nothing to allocate on ESXi; segments
    # carry the VLANs on port groups.
    for node in plan.networks():
        lines += ["", 'module "%s" {' % plan.ref(node["id"])] + align([
            ("source", '"./modules/esxi/network"'),
            ("name", '"%s"' % plan.tag(node["id"])),
        ]) + ["}"]

    for node in plan.segments():
        lines += ["", 'module "%s" {' % plan.ref(node["id"])] + align([
            ("source", '"./modules/esxi/segment"'),
            ("name", '"%s"' % plan.tag(node["id"])),
            ("host_system_id", "data.vsphere_host.host.id"),
            ("datacenter_id", "data.vsphere_datacenter.dc.id"),
            ("vswitch", "var.vswitch"),
            ("vlan_id", str(seg_vlan[node["id"]])),
        ]) + ["}"]

    for node in plan.hosts():
        segment = plan.primary_segment(node)
        windows = is_windows(node)
        cores, memory = DEFAULT_MACHINE.get(node["kind"], (2, 4096))
        cidr = plan.ctx.overlay(segment, "cidr")
        pairs = [
            ("source", '"./modules/esxi/host"'),
            ("name", '"%s"' % plan.tag(node["id"])),
            ("node_id", '"%s"' % plan.tag(node["id"])),
            ("kind", '"%s"' % node["kind"]),
            ("resource_pool_id", "data.vsphere_resource_pool.pool.id"),
            ("datastore_id", "data.vsphere_datastore.ds.id"),
            ("datacenter_id", "data.vsphere_datacenter.dc.id"),
            ("network_id", "module.%s.network_id" % plan.ref(segment)),
            ("cores", str(cores)),
            ("memory", str(memory)),
            ("windows", "true" if windows else "false"),
            ("ip_address", '"%s"' % host_ip[node["id"]]),
            ("netmask", str(_prefixlen(cidr))),
            ("gateway", '"%s"' % _gateway(cidr)),
            ("ssh_public_key", "var.ssh_public_key"),
        ]
        if windows:
            pairs.append(("windows_template", "var.windows_template"))
        else:
            pairs.append(("linux_ova_url", "var.linux_ova_url"))
        disk = 120 if "exchange" in (node.get("overlay", {}).get("services") or []) else 40
        pairs.append(("disk_size", str(disk)))
        if is_range:
            pairs += [
                ("lab_password", "local.lab_password"),
                # The single platform identity (redop for ops, blueop for a
                # range): the Linux admin, the Windows local account, and the
                # Guacamole login are one account, not a separate "operator". See
                # P1.7 and naming.platform_account.
                ("operator_username", '"%s"' % plan.admin_account),
                ("guac_public_key", "tls_private_key.guacamole.public_key_openssh"),
                ("guac_private_key",
                 "tls_private_key.guacamole.private_key_openssh"
                 if node["kind"] == "jumpbox" else '""'),
            ]
        lines += ["", 'module "%s" {' % plan.ref(node["id"])] + align(pairs) + ["}"]

    if is_range:
        jumps = [n for n in plan.hosts() if n["kind"] == "jumpbox"]
        if jumps:
            jref = plan.ref(jumps[0]["id"])
            lines += [
                "",
                'output "guacamole" {',
                '  description = "The single pane of glass. Open the url and log in."',
                "  sensitive   = true",
                "  value = {",
                '    url      = "https://${module.%s.ip_address}/guacamole"' % jref,
                '    username = "%s"' % plan.admin_account,
                "    password = local.lab_password",
                "  }",
                "}",
            ]
        lines += [
            "",
            'output "lab_password" {',
            '  description = "Shared password for the operator account and the portal."',
            "  sensitive   = true",
            "  value       = local.lab_password",
            "}",
        ]

    return "\n".join(lines) + "\n"


