DEFAULT_MACHINE = {
    "collector": (2, 4096),
    "operator": (2, 4096),
    "dc": (2, 4096),
    "srv": (2, 4096),
    "wks": (2, 2048),
    "siem": (4, 8192),
}


def is_windows(node):
    os_ = node.get("overlay", {}).get("os", "")
    if node["kind"] == "operator":
        return os_.startswith("windows")
    return os_.startswith("windows") or (
        node["kind"] in ("dc", "srv", "wks")
        and not os_.startswith(("debian", "ubuntu", "linux")))


