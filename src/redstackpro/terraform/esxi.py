"""The ESXi / vSphere backend (hashicorp/vsphere).

On-prem like Proxmox, but vSphere has no cloud-image download and no managed
per-VM firewall. So (Michael's calls, 2026-08-28): a Linux host deploys from an
OVA URL the operator supplies, a Windows host clones a prepared template, and
segmentation is VLAN-only on port groups with no firewall resource (host-level or
appliance firewalling is the operator's, stated in firewall.tf). Each host takes
a static address from its segment, customized in at deploy. See 0015.
"""

