def _firewall(plan):
    """vSphere has no managed per-VM firewall, so there is nothing to render.
    Segments isolate at layer 2 by VLAN (the port groups in the segment module);
    any east-west or ingress filtering is host-level or an appliance, which
    redStackPRO does not control or declare here. Michael's call, 2026-08-28."""
    return (
        "# Generated by redStackPRO. Do not edit.\n"
        "# vSphere exposes no managed per-VM firewall, so no rules are rendered.\n"
        "# Segments isolate at layer 2 by VLAN (see the port groups in main.tf).\n"
        "# Host-level or appliance firewalling is the operator's, by design.\n")
